"""
Font16 -- the hand-drawn 12x12 atlas (alienraid12x12.png) re-authored as
CODE at 16x16, in the same procedural style as renderer/sprites.py.

charset_map.json is the ground truth for the character set:
* every key of its ``char_map`` (state 'char' cells) is a drawable glyph
  and is re-authored here: 0-9, a-z, A-Z, the punctuation row,
  ``@ [ \\ ] ^ _ ` { | } ~`` and the 14 specials
  arrows, triangles, double arrows, checkboxes, radios;
* cells with ``"state": "sprite"`` (leftover mob/terrain icons in the old
  atlas, e.g. cells 11_1, 12_1, 16_2, 25_1...) are IGNORED -- they were
  never text and are not reproduced here;
* ``"state": "empty"`` cells are blank and ignored likewise.

Each glyph is authored as a 5x7 ink map ('#' = ink) and painted as 2x2
blocks -- an integer x2 scale, so strokes are a chunky 2px, matching the
hand-drawn weight without any non-integer stretching -- centred in the
16x16 cell (3px side margins, 1px top/bottom).

The public API mirrors FontRenderer (draw_text/draw_char on a 16px tile
grid, vertical_center for bar labels, '?' fallback for unknown chars),
so it can replace the bitmap font wherever a 16px UI grid is wanted.

Run ``python -m renderer.font16`` to render font16_sheet.png and eyeball
every glyph.
"""

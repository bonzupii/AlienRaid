def has_glyph(ch):
    """True if the character is part of the in-use charset (mirrors
    charset_map.json's char_map). Space is drawable (blank)."""
    return ch == ' ' or ch in GLYPHS


def _paint_glyph(surf, ch, color):
    if ch == ' ':
        return  # space is a drawable blank, never a '?' fallback
    rows = GLYPHS.get(ch)
    if rows is None:
        rows = GLYPHS['?']
    for ry, row in enumerate(rows):
        for cx, ink in enumerate(row):
            if ink == '#':
                pygame.draw.rect(surf, color,
                                 (_OX + cx * 2, _OY + ry * 2, 2, 2))


class Font16:
    """Procedural 16x16 font. Drop-in API for FontRenderer on a 16px grid."""

    def __init__(self, tile=TILE):
        self.tile = tile
        self._cache = {}

    def glyph(self, ch, color):
        if isinstance(ch, int):
            ch = chr(ch)
        if ch not in GLYPHS and ch != ' ':
            ch = '?'
        key = (ch, color)
        surf = self._cache.get(key)
        if surf is None:
            surf = pygame.Surface((TILE, TILE), pygame.SRCALPHA)
            _paint_glyph(surf, ch, color + (255,))
            self._cache[key] = surf
        return surf

    def _ink_rows(self, ch):
        rows = GLYPHS.get(ch)
        if rows is None:
            return None
        ys = [y for y, row in enumerate(rows) if '#' in row]
        if not ys:
            return None
        return (min(ys) * 2 + _OY, max(ys) * 2 + _OY + 1)

    def draw_char(self, surface, code, x, y, color, y_px_offset=0):
        ch = chr(code) if isinstance(code, int) else code
        if ch == ' ':
            return
        surface.blit(self.glyph(ch, color),
                     (x * self.tile, y * self.tile + y_px_offset))

    def draw_text(self, surface, text, x, y, color, vertical_center=False):
        text = str(text)
        y_px_offset = 0
        if vertical_center:
            rows = [r for r in (self._ink_rows(ch) for ch in text) if r]
            if rows:
                top = min(r[0] for r in rows)
                bottom = max(r[1] for r in rows)
                y_px_offset = (self.tile - (bottom - top)) // 2 - top
        for i, ch in enumerate(text):
            self.draw_char(surface, ch, x + i, y, color, y_px_offset=y_px_offset)


